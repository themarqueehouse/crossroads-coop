// The gym and story-battle passes covered the fights. These are the rest:
// the cutscenes the game starts at you off a trigger tile or an on-frame
// table, which are exactly the ones a partner's console never hears about
// on its own. Several of them move a shared var on the way out, so without
// mirroring the first player through takes the scene away from the second.
//
// Selected rather than swept: a script qualifies only if it locks the
// player AND has dialogue or a battle in it. Position setters, map-name
// popups, exit guards and "you cannot pass" refusals are left alone -- a
// refusal is a message you dismiss, not a scene. So are the battle
// facilities, the Safari Zone and anything with a turnstile: those are
// each player's own business and mirroring one charges your partner.
//
// Numbered from 2000, clear of the gym leaders at 200, the gym trainers
// at 300 and the story battles at 500.

